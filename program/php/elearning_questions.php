function getElearningAttemptLabel($attemptNo)
{
	return ($attemptNo <= 1) ? 'ก่อนเรียน' : 'หลังเรียน';
}

function getElearningAnswer($row, $question)
{
	$field = $question['field'];

	if ($question['type'] == 'checkbox') {
		$raw = trim((string)($row[$field] ?? ''));

		if ($raw == '') {
			return array();
		}

		$answer = array();
		foreach (explode(',', $raw) as $value) {
			$value = intval(trim($value));
			if ($value > 0) {
				$answer[] = $value;
			}
		}

		$answer = array_values(array_unique($answer));
		sort($answer);
		return $answer;
	}

	return intval($row[$field] ?? 0);
}

function isElearningAnswerCorrect($row, $question)
{
	$answer = getElearningAnswer($row, $question);

	if ($question['type'] == 'checkbox') {
		$correct = $question['correct'];
		sort($correct);
		return $answer == $correct;
	}

	return intval($answer) == intval($question['correct']);
}

function getElearningScoreText($score)
{
	if ($score >= 12) {
		return 'ผ่านเกณฑ์';
	}
	if ($score < 5) {
		return 'ควรศึกษาเพิ่มเติม';
	}
	if ($score < 7) {
		return 'มีความรู้ระดับเริ่มต้น';
	}
	return 'มีความรู้ระดับปานกลาง';
}
